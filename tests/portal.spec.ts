test('landing and completed answer pass WCAG A/AA automated checks', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  const landing = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
  expect(landing.violations).toEqual([])
  await instantDemo(page)
  await page.getByRole('button', { name: /What is behind the conversion decline/ }).click()
  await expect(page.getByRole('heading', { name: 'The decline is concentrated in mobile-web verification.' })).toBeVisible()
  await expect(page.locator('.recharts-surface').first()).toBeVisible()
  await page.getByRole('button', { name: 'Pause animation' }).click()
  const answer = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
  expect(answer.violations).toEqual([])
  await expect(page.locator('.investigation-theater')).toBeVisible()
  const workflow = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
  expect(workflow.violations).toEqual([])
  await page.getByRole('button', { name: 'Accounts & growth: Complete. Inspect evidence' }).click()
  const evidence = await new AxeBuilder({ page }).withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()
  expect(evidence.violations).toEqual([])
  expect(errors).toEqual([])
})

test('sources actually fly, packets move along connections, and discoveries expand the map', async ({ page }) => {
  const errors: string[] = []
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await page.getByRole('button', { name: /What is behind the conversion decline/ }).click()
  await expect(page.locator('.source-flight')).toHaveCount(2)
  const source = page.locator('.source-flight[data-source-id="accounts"]')
  const firstSource = await source.boundingBox()
  await expect.poll(async () => {
    const position = await source.boundingBox()
    return Math.hypot(position!.x - firstSource!.x, position!.y - firstSource!.y)
  }, { timeout: 2500 }).toBeGreaterThan(35)
  const packet = page.locator('[data-stream-source="accounts"] .flow-packet.data')
  const firstPacket = await packet.boundingBox()
  await expect.poll(async () => {
    const position = await packet.boundingBox()
    return position && firstPacket ? Math.hypot(position.x - firstPacket.x, position.y - firstPacket.y) : 0
  }, { timeout: 2000 }).toBeGreaterThan(15)
  await expect(source.locator('.floating-source-footer')).toContainText(/Pulling|Reconciling/, { timeout: 3000 })
  await expect(page.locator('.source-flight[data-source-id="releases"]')).toBeVisible({ timeout: 6000 })
  await expect(page.locator('.discovery-connection[data-from="journeys"][data-to="releases"]')).toHaveCount(1)
  await expect(page.locator('.source-flight[data-source-id="campaigns"]')).toBeVisible({ timeout: 7000 })
  await expect(page.getByRole('heading', { name: 'The investigation, connected' })).toBeVisible({ timeout: 15000 })
  await expect(page.locator('.source-flight')).toHaveCount(13)
  await expect(page.getByRole('button', { name: 'Replay demo', exact: true })).toBeVisible()
  expect(errors).toEqual([])
})

test('motion pause freezes the scene, replay restarts it, and cancel stops transfers', async ({ page }) => {
  await instantDemo(page)
  await page.getByRole('button', { name: /How are Roth IRA openings trending/ }).click()
  await expect(page.locator('.source-flight')).toHaveCount(1)
  await expect(page.locator('[data-source-id="accounts"]')).toBeVisible()
  await expect(page.locator('[data-source-id="releases"]')).toHaveCount(0)
  await page.getByRole('button', { name: 'Pause animation' }).click()
  expect(await page.locator('.floating-source').evaluate(element => getComputedStyle(element).animationPlayState)).toBe('paused')
  await page.getByRole('button', { name: 'Resume animation' }).click()
  expect(await page.locator('.floating-source').evaluate(element => getComputedStyle(element).animationPlayState)).toBe('running')
  await page.getByRole('button', { name: 'Replay demo', exact: true }).click()
  await expect(page.locator('.flow-packet.data')).toHaveCount(1)
  await page.getByRole('button', { name: 'Pause animation' }).click()
  expect(await page.locator('.flow-packet.data').evaluate(element => getComputedStyle(element).animationPlayState)).toBe('paused')
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(page.locator('.flow-packet')).toHaveCount(0)
  await expect(page.getByRole('heading', { name: 'Stopped, not lost.' })).toBeVisible()
})

