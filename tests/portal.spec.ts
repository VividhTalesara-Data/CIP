import { test, expect } from '@playwright/test'
import type { Page } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'

async function instantDemo(page: Page) {
  await page.getByRole('button', { name: 'Demo workspace' }).click()
  await page.getByRole('checkbox', { name: 'Simulated connector latency' }).uncheck()
  await page.getByRole('button', { name: 'Close dialog' }).click()
}

test.beforeEach(async ({ page }) => { await page.goto('/') })

test('minimal landing, role personalization, keyboard input and exact count answer', async ({ page }) => {
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Clarity startswith a question.')
  await expect(page.locator('.suggestion-card')).toHaveCount(4)
  await page.getByRole('combobox', { name: 'Business profile' }).selectOption('digital')
  await expect(page.getByRole('button', { name: /HSA account openings/ })).toBeVisible()
  await instantDemo(page)
  const input = page.getByRole('textbox', { name: 'Ask a question', exact: true })
  await input.fill('How many HSA accounts')
  await input.press('Shift+Enter')
  await input.press('End')
  await input.press('a')
  await expect(input).toHaveValue('How many HSA accounts\na')
  await input.fill('How many HSA accounts were opened this year compared with last year?')
  await input.press('Enter')
  await expect(page.getByRole('heading', { name: 'HSA openings are up 16% year to date.' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Inspect Accounts opened evidence' })).toContainText('17,400')
  await page.getByRole('button', { name: 'Inspect Accounts opened evidence' }).click()
  await expect(page.getByRole('dialog')).toContainText('Jan 1 - Nov 12, 2025')
  await expect(page.getByRole('dialog')).toContainText('Distinct account')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Inspect Accounts opened evidence' })).toBeFocused()
})

