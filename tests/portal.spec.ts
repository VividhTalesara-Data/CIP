async function loginAs(page: Page, username = 'executive') {
  if (await page.locator('.signout-button').count()) {
    if (await page.getByRole('dialog').count()) await page.keyboard.press('Escape')
    await page.getByRole('button', { name: 'Sign out', exact: true }).click()
  }
  await page.getByRole('textbox', { name: 'Username', exact: true }).fill(username)
  await page.getByLabel('Password', { exact: true }).fill('clarity-demo')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.locator('.signed-in-user')).toBeVisible()
}

